    public static func text(_ key: String, language: InterfaceLanguage) -> String {
        language == .english ? (english[key] ?? key) : key
    }

    public static func phase(_ value: ProjectPhase, language: InterfaceLanguage) -> String {
        let labels: [ProjectPhase: String] = [
            .draft: "草稿", .executing: "執行中", .reviewing: "待驗收",
            .accepted: "已套用", .rejected: "已駁回", .failed: "失敗"
        ]
        return text(labels[value] ?? value.rawValue, language: language)
    }

    public static func change(_ value: ChangeKind, language: InterfaceLanguage) -> String {
        switch value {
        case .added: return language == .english ? "Added" : "新增"
        case .modified: return language == .english ? "Modified" : "修改"
        case .deleted: return language == .english ? "Deleted" : "刪除"
        }
    }
